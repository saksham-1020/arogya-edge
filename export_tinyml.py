import os
import sys
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')
import torch
import numpy as np
from models import TCECOModel

def export_tinyml():
    checkpoint_path = os.path.join(os.path.dirname(__file__), 'tceco_checkpoint.pt')
    if not os.path.exists(checkpoint_path):
        print('[-] Checkpoint not found. Please run train.py first.')
        return
    model = TCECOModel(time_steps=200, out_classes=8)
    model.load_state_dict(torch.load(checkpoint_path, map_location='cpu'))
    model.eval()
    dummy_signal = torch.randn(1, 3, 200, dtype=torch.float32)
    dummy_temp = torch.tensor([28.0], dtype=torch.float32)
    onnx_path = os.path.join(os.path.dirname(__file__), 'tceco_edge.onnx')
    torch.onnx.export(model, (dummy_signal, dummy_temp), onnx_path, input_names=['bio_signals', 'ambient_temperature'], output_names=['evidence', 'prob', 'uncertainty', 'antigen_probs'], opset_version=18, do_constant_folding=True)
    onnx_size_kb = os.path.getsize(onnx_path) / 1024.0
    print(f'[+] Exported ONNX model: {onnx_path} ({onnx_size_kb:.2f} KB)')
    c_header_path = os.path.join(os.path.dirname(__file__), 'firmware', 'tceco_weights.h')
    os.makedirs(os.path.dirname(c_header_path), exist_ok=True)
    with open(onnx_path, 'rb') as f:
        bytes_data = f.read()
    with open(c_header_path, 'w') as f:
        f.write('// Auto-generated by T-CECO TinyML Exporter for IITI CPS-DRISHTI\n')
        f.write('// Architecture: Thermodynamically-Compensated Evidential Causal Operator\n')
        f.write('// Target: ESP32-S3 / STM32 (ARM Cortex-M4) Embedded Flash\n\n')
        f.write(f'#ifndef TCECO_WEIGHTS_H\n#define TCECO_WEIGHTS_H\n\n')
        f.write(f'const unsigned int g_tceco_model_size = {len(bytes_data)};\n\n')
        f.write('const unsigned char g_tceco_model_data[] __attribute__((aligned(4))) = {\n  ')
        for i, b in enumerate(bytes_data):
            f.write(f'0x{b:02x}, ')
            if (i + 1) % 16 == 0:
                f.write('\n  ')
        f.write('\n};\n\n#endif // TCECO_WEIGHTS_H\n')
    print(f'[+] Generated Embedded C-Header: {c_header_path} ({len(bytes_data) / 1024.0:.2f} KB)')
    print('[+] Ready for direct compilation into ESP32 / STM32 microcontroller firmware!')
if __name__ == '__main__':
    export_tinyml()
